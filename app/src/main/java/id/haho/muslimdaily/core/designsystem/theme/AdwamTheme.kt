/**
 * Adwam's theme: the shared haho-design system ([HahoTheme]: palettes, glass, Plus Jakarta Sans,
 * spacing, motion) plus what only Adwam needs, the Arabic type scale and the gold highlight and
 * count-complete colours.
 */
@Composable
fun AdwamTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    dynamicColor: Boolean = false,
    palette: HahoPalette = HahoPalette.Default,
    arabicScale: Float = 1f,
    translationScale: Float = 1f,
    glass: Boolean = true,
    arabicFont: ArabicFont = ArabicFont.NASKH,
    content: @Composable () -> Unit,
) {
    val dark = themeMode.isDark()
    HahoTheme(
        palette = palette,
        themeMode = themeMode,
        glass = glass,
        dynamicColor = dynamicColor,
        readingScale = translationScale,
    ) {
        val arabic = remember(arabicFont, arabicScale) { ArabicTypography.of(arabicFont).scaled(arabicScale) }
        // Material You keeps the system's tertiary for the accent; every other case uses the fixed values.
        val scheme = MaterialTheme.colorScheme
        val systemAccent = dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S
        val extended = remember(palette, dark, systemAccent, scheme) {
            val fixed = extendedColors(palette, dark)
            if (systemAccent) {
                fixed.copy(
                    accent = scheme.tertiary,
                    onAccent = scheme.onTertiary,
                    accentContainer = scheme.tertiaryContainer,
                    onAccentContainer = scheme.onTertiaryContainer,
                )
            } else {
                fixed
            }
        }
        CompositionLocalProvider(
            LocalArabicTypography provides arabic,
            LocalExtendedColors provides extended,
            content = content,
        )
    }
}

/** Adwam's theme values beyond [HahoTheme]: Arabic typography, the gold roles and the third accent. */
object AdwamTheme {
    val arabic: ArabicTypography
        @Composable @ReadOnlyComposable get() = LocalArabicTypography.current
    val colors: ExtendedColors
        @Composable @ReadOnlyComposable get() = LocalExtendedColors.current
}

/** Sizes only Adwam's screens use; the shared ones are in [HahoTheme.dimens]. */
object AdwamDimens {
    val playerMainButton: Dp = 72.dp
    /** Play in the compact dua player: with 48dp skip buttons the bar is about 64dp tall. */
    val playerCompactButton: Dp = 56.dp
    val completeDisc: Dp = 56.dp
    val highlightUnderline: Dp = 2.dp
    val timelineDot: Dp = 10.dp
    /** The rail column and the filled dot of a done step: dot and tick in one circle. */
    val timelineCheck: Dp = 20.dp
    val placeholderWordHeight: Dp = 28.dp
}

/** Gold, used only as a fill or a non-text indicator. */
internal val Gold = Color(0xFFC9A227)

/** Gold tones 90 / 30 / 10 (the active-phrase fill and the text on it). */
private val GoldTone90 = Color(0xFFFFE08E)
private val GoldTone30 = Color(0xFF584400)
private val GoldTone10 = Color(0xFF241A00)

/** The gold for small marks on a light surface (dots, the crescent): 3.7:1 on the tinted containers, where raw gold is 2:1. */
private val GoldMarkLight = Color(0xFF93750F)

/** Colour roles M3 does not cover. Gold appears only as fill or non-text indicator. */
@Immutable
data class ExtendedColors(
    val highlightFill: Color,
    val onHighlightFill: Color,
    val highlightIndicator: Color,
    val completeFill: Color,
    val onCompleteFill: Color,
    /** A small gold mark on the page background or a card (fasting dots, the Ramadan crescent), 3:1 or more. */
    val goldMark: Color,
    /**
     * The third accent, the 10 of 60:30:10: "this is happening now" (the countdown, the Now chip).
     * Text of 4.5:1 or more on the page and on the glass cards; never for body or Arabic text, errors or counts.
     * Values and rules: `docs/accent.md`.
     */
    val accent: Color,
    val onAccent: Color,
    val accentContainer: Color,
    val onAccentContainer: Color,
)

/** One palette and mode of the accent: accent, onAccent, container, onContainer (docs/accent.md, generated by tools/accent_palette.py). */
private class AccentSet(accent: Long, onAccent: Long, container: Long, onContainer: Long) {
    val accent = Color(accent)
    val onAccent = Color(onAccent)
    val container = Color(container)
    val onContainer = Color(onContainer)
}

private fun accentSet(palette: HahoPalette, dark: Boolean): AccentSet = when (palette) {
    HahoPalette.TEAL ->
        if (dark) AccentSet(0xFFC7B6FE, 0xFF000000, 0xFF352E4A, 0xFFC5BBE6) else AccentSet(0xFF6D54A8, 0xFFFFFFFF, 0xFFE6E0FE, 0xFF4D4468)
    HahoPalette.NAVY ->
        if (dark) AccentSet(0xFFA2CE72, 0xFF000000, 0xFF2A381C, 0xFFB4C9A1) else AccentSet(0xFF476E04, 0xFFFFFFFF, 0xFFDBEBCC, 0xFF3E502C)
    HahoPalette.FOREST ->
        if (dark) AccentSet(0xFFF0A8F4, 0xFF000000, 0xFF402A41, 0xFFD7B6D8) else AccentSet(0xFF8C4A90, 0xFFFFFFFF, 0xFFF5DBF5, 0xFF5B3F5C)
    HahoPalette.SLATE ->
        if (dark) AccentSet(0xFF28D6DF, 0xFF000000, 0xFF083A3D, 0xFF93CDD0) else AccentSet(0xFF066E73, 0xFFFFFFFF, 0xFFC3EEF0, 0xFF145154)
    HahoPalette.OLIVE ->
        if (dark) AccentSet(0xFFFFA9D2, 0xFF000000, 0xFF462836, 0xFFE0B2C6) else AccentSet(0xFF9C4372, 0xFFFFFFFF, 0xFFFDD9E9, 0xFF633D4F)
    HahoPalette.ROSE ->
        if (dark) AccentSet(0xFF73CDFF, 0xFF000000, 0xFF163749, 0xFF9CC8E3) else AccentSet(0xFF036A94, 0xFFFFFFFF, 0xFFC9EAFF, 0xFF254E65)
    HahoPalette.LAVENDER ->
        if (dark) AccentSet(0xFF5ED8A9, 0xFF000000, 0xFF163B2C, 0xFF9DCEB7) else AccentSet(0xFF047252, 0xFFFFFFFF, 0xFFCAEFDD, 0xFF255341)
    HahoPalette.PEACH ->
        if (dark) AccentSet(0xFFA5C2FF, 0xFF000000, 0xFF26324D, 0xFFAEC1E9) else AccentSet(0xFF3F60AE, 0xFFFFFFFF, 0xFFD9E5FE, 0xFF39486A)
}

/**
 * The gold roles for [palette]. They are the same in every palette except the light-mode
 * underline and [ExtendedColors.goldMark], which use darker tones because raw gold on a light surface is below 3:1.
 * Dynamic colour does not change them.
 */
fun extendedColors(palette: HahoPalette, dark: Boolean): ExtendedColors {
    val accent = accentSet(palette, dark)
    return ExtendedColors(
        highlightFill = if (dark) GoldTone30 else GoldTone90,
        onHighlightFill = if (dark) GoldTone90 else GoldTone10,
        highlightIndicator = if (dark) Gold else colorSchemeFor(palette, dark = false).primary,
        completeFill = Gold,
        onCompleteFill = GoldTone10,
        goldMark = if (dark) Gold else GoldMarkLight,
        accent = accent.accent,
        onAccent = accent.onAccent,
        accentContainer = accent.container,
        onAccentContainer = accent.onContainer,
    )
}

val LocalExtendedColors = staticCompositionLocalOf { extendedColors(HahoPalette.Default, dark = false) }
