#!/usr/bin/env python3
"""Converts Material Symbols Rounded (weight 300) SVGs into Android vector drawables.

    cd tools/icons && npm ci && python3 build_icons.py

Source: the @material-symbols/svg-300 npm package (Apache 2.0). Only the icons listed in
ICONS are converted, plus a filled variant for those in FILLED (used for selected states).
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "node_modules/@material-symbols/svg-300/rounded"
OUT = HERE.parent.parent / "app/src/main/res/drawable"

ICONS = [
    "wb_twilight", "menu_book", "record_voice_over", "settings",
    "play_arrow", "pause", "stop", "skip_next", "skip_previous", "replay", "repeat", "speed",
    "headphones", "search", "close", "arrow_back", "chevron_right",
    "check", "check_circle", "drag_indicator", "visibility", "visibility_off", "tune", "restart_alt",
    "location_on", "my_location", "schedule", "notifications", "notifications_off", "dark_mode",
    "light_mode", "text_fields", "translate", "info", "flag", "bookmark_add", "bookmark_added",
    "ios_share", "upload", "download", "mosque", "luggage", "warning", "block", "add",
    "remove", "more_vert", "history", "timer", "verified", "autorenew", "keyboard_arrow_up",
    "keyboard_arrow_down", "wb_sunny", "bedtime", "alarm", "calendar_month",
    "auto_stories", "done_all", "delete", "language", "contrast", "mail", "lock", "graphic_eq",
    "mobile_off", "nightlight", "edit", "sunny", "partly_cloudy_day", "brightness_5", "volume_up",
    "volume_off", "fast_forward", "self_improvement", "inbox", "help", "event_repeat",
    "location_off", "travel_explore", "format_list_numbered", "touch_app", "music_off",
]
FILLED = ["wb_twilight", "menu_book", "record_voice_over", "settings", "check_circle", "bookmark_added"]
MIRRORED = {"arrow_back", "chevron_right", "skip_next", "skip_previous", "fast_forward", "ios_share"}

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded, weight 300{fill_note}. Generated by tools/icons/build_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:autoMirrored="{mirrored}"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path
            android:fillColor="@android:color/black"
            android:pathData="{path}" />
    </group>
</vector>
"""


def convert(name: str, filled: bool) -> None:
    svg_name = f"{name}-fill.svg" if filled else f"{name}.svg"
    svg = (SRC / svg_name).read_text()
    view_box = re.search(r'viewBox="([^"]+)"', svg).group(1)
    if view_box != "0 -960 960 960":
        raise SystemExit(f"{svg_name}: unexpected viewBox {view_box}")
    paths = re.findall(r'<path[^>]* d="([^"]+)"', svg)
    if len(paths) != 1:
        raise SystemExit(f"{svg_name}: expected one path, found {len(paths)}")
    out_name = f"ic_{name}{'_fill' if filled else ''}.xml"
    (OUT / out_name).write_text(TEMPLATE.format(
        fill_note=", filled" if filled else "",
        mirrored="true" if name in MIRRORED else "false",
        path=paths[0],
    ))


def main() -> int:
    if not SRC.exists():
        print("Run `npm ci` in tools/icons first", file=sys.stderr)
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    missing = [n for n in ICONS if not (SRC / f"{n}.svg").exists()]
    if missing:
        print("Missing icons: " + ", ".join(missing), file=sys.stderr)
        return 1
    for name in ICONS:
        convert(name, filled=False)
    for name in FILLED:
        convert(name, filled=True)
    print(f"Wrote {len(ICONS) + len(FILLED)} drawables to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
