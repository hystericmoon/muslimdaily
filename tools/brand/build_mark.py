#!/usr/bin/env python3
"""Builds the Adwam mark (Wasl) and writes the Android drawables that use it.

    pip install shapely && python3 tools/brand/build_mark.py

The mark is one line along the baseline that loops once and keeps going, then a gold dot.
Rules (also in the brand book): the line is exactly as thick as the dot is wide; the dot sits half
a line-width past the line's end; the loop leans forward (shear 0.12, about 7 degrees) while the
baseline stays level; the line runs unbroken under the loop; joins are bracketed at 0.24 of the
line width. The outline is computed here, so every drawable is a filled shape, not a stroke.

Writes:
  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive icon foreground (line + gold dot)
  app/src/main/res/drawable/ic_launcher_monochrome.xml   themed icon (one ink; Android tints it)
  app/src/main/res/drawable/ic_notification.xml          status-bar glyph (white)
  wear/src/main/res/drawable/ic_tile.xml                 Wear app and tile glyph (white)
  docs/brand/adwam-mark.svg                              the master outline (teal + gold)
"""
import re
from pathlib import Path

from shapely.geometry import LineString, Point
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[2]
TEAL, GOLD = "#1F5F5B", "#C9A227"

# Centreline of the line, drawn in a 512 box with the baseline at y = 350.
CENTRELINE = ("M56,350 H170 C266,350 352,296 352,214 C352,138 300,94 244,94 "
              "C186,94 140,138 140,200 C140,294 226,350 326,350 H380")
BASE, W, LEAN, BRACKET = 350.0, 64.0, 0.12, 0.24


def _cubic(p0, p1, p2, p3, n=160):
    pts = []
    for i in range(n + 1):
        t = i / n
        u = 1 - t
        pts.append((u ** 3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t ** 3 * p3[0],
                    u ** 3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t ** 3 * p3[1]))
    return pts


def _centreline():
    toks = re.findall(r"[MHC]|-?\d+\.?\d*", CENTRELINE)
    pts, cur, i = [], None, 0
    while i < len(toks):
        c = toks[i]
        i += 1
        if c == "M":
            cur = (float(toks[i]), float(toks[i + 1]))
            i += 2
            pts.append(cur)
        elif c == "H":
            cur = (float(toks[i]), cur[1])
            i += 1
            pts.append(cur)
        else:
            p1 = (float(toks[i]), float(toks[i + 1]))
            p2 = (float(toks[i + 2]), float(toks[i + 3]))
            p3 = (float(toks[i + 4]), float(toks[i + 5]))
            i += 6
            pts += _cubic(cur, p1, p2, p3)[1:]
            cur = p3
    return [(x + LEAN * (BASE - y), y) for x, y in pts]  # lean the loop; the baseline is unchanged


def mark():
    pts = _centreline()
    r = W / 2
    loop = LineString(pts).buffer(r, cap_style="round", join_style="round", quad_segs=64)
    line = LineString([(pts[0][0], BASE), (pts[-1][0], BASE)]).buffer(r, cap_style="round", quad_segs=64)
    k = BRACKET * W
    shape = unary_union([loop, line]).buffer(k, quad_segs=64).buffer(-k, quad_segs=64)
    dot = Point(pts[-1][0] + r + 0.5 * W + r, BASE).buffer(r, quad_segs=96)
    return shape, dot


def path_data(geom, ox, oy, s, tol, fmt):
    polys = [geom] if geom.geom_type == "Polygon" else list(geom.geoms)
    out = []
    for p in polys:
        for ring in [p.exterior, *p.interiors]:
            cs = list(ring.simplify(tol).coords)[:-1]
            out.append("M" + " L".join(f"{fmt % ((x - ox) * s)},{fmt % ((y - oy) * s)}" for x, y in cs) + "Z")
    return " ".join(out)


def vector(shape, dot, viewport, width_units, line_color, dot_color, size_dp, comment):
    """The mark centred in a square viewport, width_units wide."""
    x0, y0, x1, y1 = unary_union([shape, dot]).bounds
    s = width_units / (x1 - x0)
    ox = (x0 + x1) / 2 - viewport / 2 / s
    oy = (y0 + y1) / 2 - viewport / 2 / s
    tol = 0.03 * viewport / 108 / s  # at most ~0.03 units of a 108-unit canvas off the true outline
    line_d = path_data(shape, ox, oy, s, tol, "%.3f")
    dot_d = path_data(dot, ox, oy, s, tol, "%.3f")
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/brand/build_mark.py; do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
    <path
        android:fillColor="{line_color}"
        android:fillType="evenOdd"
        android:pathData="{line_d}" />
    <path
        android:fillColor="{dot_color}"
        android:pathData="{dot_d}" />
</vector>
"""


def main():
    shape, dot = mark()
    out = {
        # 56 of 108 units wide: every corner of the mark stays inside the 66-unit safe-zone circle.
        "app/src/main/res/drawable/ic_launcher_foreground.xml": vector(
            shape, dot, 108, 56, "@color/launcher_foreground", "@color/launcher_accent", 108,
            "Adaptive icon foreground: the Adwam mark (Wasl), parchment line and gold dot."),
        "app/src/main/res/drawable/ic_launcher_monochrome.xml": vector(
            shape, dot, 108, 56, "#FF000000", "#FF000000", 108,
            "Themed (monochrome) icon: the Adwam mark in one ink; the launcher tints it."),
        "app/src/main/res/drawable/ic_notification.xml": vector(
            shape, dot, 24, 22, "@android:color/white", "@android:color/white", 24,
            "Notification glyph: the Adwam mark, monochrome."),
        "wear/src/main/res/drawable/ic_tile.xml": vector(
            shape, dot, 24, 22, "#FFFFFFFF", "#FFFFFFFF", 24,
            "Wear app and tile glyph: the Adwam mark, monochrome."),
    }
    for rel, text in out.items():
        (ROOT / rel).write_text(text)
    x0, y0, x1, y1 = unary_union([shape, dot]).bounds
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{x1 - x0:.2f}" height="{y1 - y0:.2f}" '
           f'viewBox="0 0 {x1 - x0:.2f} {y1 - y0:.2f}">'
           f'<path d="{path_data(shape, x0, y0, 1, 0.12, "%.2f")}" fill="{TEAL}" fill-rule="evenodd"/>'
           f'<path d="{path_data(dot, x0, y0, 1, 0.12, "%.2f")}" fill="{GOLD}"/></svg>')
    (ROOT / "docs/brand/adwam-mark.svg").write_text(svg)
    print("Wrote", len(out) + 1, "files")


if __name__ == "__main__":
    main()
